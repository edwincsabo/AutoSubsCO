const { contextBridge, ipcRenderer } = require('electron');
const invoke = async (channel, ...args) => {
  const result = await ipcRenderer.invoke(channel, ...args);
  if (!result.ok) throw new Error(result.error);
  return result.value;
};
contextBridge.exposeInMainWorld('autosubs', Object.freeze({
  state: () => invoke('state'),
  importGraphic: options => invoke('import-graphic',options),
  title: (id,value,png,options) => invoke('title',id,value,png,options),
  graphicEdit: (id,value) => invoke('graphic-edit',id,value),
  importMedia: options => invoke('import-media',options),
  newProject: () => invoke('new-project'),
  restore: () => invoke('restore'),
  dismissRecovery: () => invoke('dismiss-recovery'),
  undo: () => invoke('undo'),
  redo: () => invoke('redo'),
  clipAction: (action,id,patch) => invoke('clip-action',action,id,patch),
  audioMix: (id,value) => invoke('audio-mix',id,value),
  audioPoint: (action,id,value) => invoke('audio-point',action,id,value),
  autoDuck: options => invoke('auto-duck',options),
  prepareFindReplace: options => invoke('prepare-find-replace',options),
  discardFindReplace: id => invoke('discard-find-replace',id),
  applyFindReplace: (id,ids) => invoke('apply-find-replace',id,ids),
  prepareAlignment: options => invoke('prepare-alignment',options),
  discardAlignment: id => invoke('discard-alignment',id),
  applyAlignment: (id,cueIds) => invoke('apply-alignment',id,cueIds),
  prepareTextCut: options => invoke('prepare-text-cut',options),
  applyTextCut: id => invoke('apply-text-cut',id),
  discardTextCut: id => invoke('discard-text-cut',id),
  precision: (action,ids,value) => invoke('precision',action,ids,value),
  sequence: (preset,fps) => invoke('sequence',preset,fps),
  settings: values => invoke('settings',values),
  addExisting: (id,options) => invoke('add-existing',id,options),
  visual: (id,patch) => invoke('visual',id,patch),
  keyframe: (action,id,value) => invoke('keyframe',action,id,value),
  separate: id => invoke('separate',id),
  stemMode: (id,mode) => invoke('stem-mode',id,mode),
  speakers: options => invoke('speakers',options),
  speakerUpdate: (id,name,color) => invoke('speaker-update',id,name,color),
  translate: (from,to) => invoke('translate',from,to),
  captionView: value => invoke('caption-view',value),
  downloadResource: id => invoke('download-resource',id),
  packageProject: () => invoke('package-project'),
  openPackage: () => invoke('open-package'),
  thumbnail: id => invoke('thumbnail',id),
  compare: options => invoke('compare',options),
  applyComparison: index => invoke('apply-comparison',index),
  openProject: () => invoke('open-project'),
  saveProject: () => invoke('save-project'),
  saveProjectAs: () => invoke('save-project-as'),
  openRecent: id => invoke('open-recent',id),
  locateRecent: id => invoke('locate-recent',id),
  forgetRecent: id => invoke('forget-recent',id),
  projectVersions: () => invoke('project-versions'),
  previewVersion: id => invoke('preview-version',id),
  restoreVersion: token => invoke('restore-version',token),
  edit: patch => invoke('edit', patch),
  transcribe: options => invoke('transcribe', options),
  downloadModel: id => invoke('download-model', id),
  cancel: () => invoke('cancel'),
  exportSubtitles: format => invoke('export-subtitles', format),
  exportVideo: mode => invoke('export-video', mode),
  importSubtitles: () => invoke('import-subtitles'),
  configureTool: name => invoke('configure-tool', name),
  reveal: () => invoke('reveal'),
  waveform: id => invoke('waveform',id),
  readyToClose: error => invoke('close-ready', error),
  onBeforeClose: callback => { const listener = () => callback(); ipcRenderer.on('before-close', listener); return () => ipcRenderer.removeListener('before-close', listener); },
  onProgress: callback => { const listener = (_, data) => callback(data); ipcRenderer.on('progress', listener); return () => ipcRenderer.removeListener('progress', listener); },
  onCommand: callback => { const listener = (_, data) => callback(data); ipcRenderer.on('command', listener); return () => ipcRenderer.removeListener('command', listener); }
}));
